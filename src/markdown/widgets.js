/**
 * Turns the inert placeholders left by ./plugins.js into formulas, diagrams
 * and charts. This runs on already sanitized DOM: the source of each widget is
 * read as plain text and handed to its library; it is never parsed as HTML.
 *
 * Every library is loaded on demand, so a post without diagrams never pays for them.
 */

const SAFE_LINK = /^(?:https?:|mailto:)/i;

function sourceOf(el) {
    return el.textContent || "";
}

function showError(el, prefix, error) {
    const pre = document.createElement("pre");
    pre.className = "md-widget-error";
    const message = error && (error.str || error.message) ? (error.str || error.message) : String(error);
    pre.textContent = `${prefix}: ${message}`;
    el.replaceWith(pre);
}

/* --------------------------------------------------------------------- math */

async function renderMath(nodes) {
    const [{ default: katex }] = await Promise.all([
        import("katex"),
        import("katex/dist/katex.min.css")
    ]);
    for (const el of nodes) {
        const tex = sourceOf(el);
        try {
            katex.render(tex, el, {
                displayMode: el.getAttribute("data-md-display") === "true",
                throwOnError: false,
                errorColor: "#cc0000",
                // \href, \includegraphics, \htmlClass & co. stay disabled
                trust: false,
                strict: "ignore",
                maxExpand: 1000,
                maxSize: 100
            });
        }
        catch (err) {
            el.textContent = `${tex} (${err && err.message ? err.message : err})`;
            el.classList.add("md-widget-error");
        }
        el.removeAttribute("data-md-widget");
    }
}

/* ------------------------------------------------------------------ mermaid */

let mermaidReady = null;
let mermaidId = 0;

function loadMermaid() {
    if (mermaidReady === null) {
        mermaidReady = import("mermaid").then(({ default: mermaid }) => {
            mermaid.initialize({
                startOnLoad: false,
                // "strict": labels are escaped and click/href bindings are disabled
                securityLevel: "strict",
                theme: "default"
            });
            return mermaid;
        });
    }
    return mermaidReady;
}

async function renderMermaid(nodes, isStale) {
    const mermaid = await loadMermaid();
    for (const el of nodes) {
        if (isStale()) return;
        const id = `md-mermaid-${++mermaidId}`;
        try {
            const { svg } = await mermaid.render(id, sourceOf(el));
            if (isStale()) return;
            const box = document.createElement("div");
            box.className = "md-mermaid";
            box.innerHTML = svg; // generated by mermaid in strict mode, not by the post
            el.replaceWith(box);
        }
        catch (err) {
            // mermaid can leave its scratch element behind when parsing fails
            document.getElementById(id)?.remove();
            document.getElementById(`d${id}`)?.remove();
            showError(el, "mermaid", err);
        }
    }
}

/* ------------------------------------------------------------------ echarts */

function clampSize(value, fallback) {
    const n = Number(value);
    if (!Number.isFinite(n) || n <= 0) return fallback;
    return Math.min(Math.max(Math.round(n), 50), 2000);
}

/**
 * Chart options come straight from the post, so drop everything that could
 * make ECharts write HTML or navigate: tooltips are drawn on the canvas
 * instead of as HTML, and title links are removed.
 */
const ECHARTS_DROPPED_KEYS = new Set([
    "link", "sublink", "target", "subtarget", "extraCssText", "className",
    "appendToBody", "appendTo", "renderMode", "enterable", "__proto__",
    "constructor", "prototype"
]);

export function sanitizeChartOption(value, depth = 0) {
    if (depth > 32) return undefined;
    if (Array.isArray(value)) {
        return value.map(item => sanitizeChartOption(item, depth + 1));
    }
    if (value !== null && typeof value === "object") {
        const out = {};
        for (const key of Object.keys(value)) {
            if (ECHARTS_DROPPED_KEYS.has(key)) continue;
            const clean = sanitizeChartOption(value[key], depth + 1);
            if (key === "tooltip" && clean !== null && typeof clean === "object" && !Array.isArray(clean)) {
                clean.renderMode = "richText";
            }
            out[key] = clean;
        }
        return out;
    }
    return value;
}

async function renderCharts(nodes, isStale, disposers) {
    const echarts = await import("./echarts");
    for (const el of nodes) {
        if (isStale()) return;
        let json;
        try {
            json = JSON.parse(sourceOf(el));
            if (json === null || typeof json !== "object" || Array.isArray(json)) {
                throw new SyntaxError("the chart definition must be a JSON object");
            }
        }
        catch (err) {
            showError(el, "echarts complains", err);
            continue;
        }
        const box = document.createElement("div");
        box.className = "md-echarts";
        box.style.width = `${clampSize(json.width, 500)}px`;
        box.style.height = `${clampSize(json.height, 400)}px`;
        el.replaceWith(box);
        try {
            const option = sanitizeChartOption(json);
            delete option.width;
            delete option.height;
            // a global tooltip always exists so that its HTML mode can never be the default
            option.tooltip = { ...(option.tooltip || { show: false }), renderMode: "richText" };
            const chart = echarts.init(box, null, { renderer: "canvas" });
            disposers.push(() => chart.dispose());
            chart.setOption(option);
        }
        catch (err) {
            showError(box, "echarts complains", err);
        }
    }
}

/* ---------------------------------------------------------------- flowchart */

async function renderFlowcharts(nodes, isStale) {
    const { default: flowchart } = await import("flowchart.js");
    for (const el of nodes) {
        if (isStale()) return;
        const box = document.createElement("div");
        box.className = "md-flowchart";
        try {
            const chart = flowchart.parse(sourceOf(el));
            for (const key of Object.keys(chart.symbols || {})) {
                const symbol = chart.symbols[key];
                // `:$name` would call window[name] on click: never from a post
                symbol.function = null;
                if (symbol.link && !SAFE_LINK.test(String(symbol.link).trim())) {
                    symbol.link = null;
                    symbol.target = null;
                }
                else if (symbol.link) {
                    symbol.target = "_blank";
                }
            }
            el.replaceWith(box);
            chart.drawSVG(box);
            for (const a of box.querySelectorAll("a")) {
                const href = a.getAttribute("href") || a.getAttributeNS("http://www.w3.org/1999/xlink", "href") || "";
                if (!SAFE_LINK.test(href.trim())) {
                    a.removeAttribute("href");
                    a.removeAttributeNS("http://www.w3.org/1999/xlink", "href");
                }
                else {
                    a.setAttribute("target", "_blank");
                    a.setAttribute("rel", "noopener noreferrer");
                }
            }
        }
        catch (err) {
            showError(box.isConnected ? box : el, "flowchart complains", err);
        }
    }
}

/* -------------------------------------------------------------------- entry */

/**
 * @param {Element} root container holding sanitized post content
 * @param {() => boolean} isStale returns true once `root` shows other content
 * @returns {Promise<() => void>} cleanup function releasing chart instances
 */
export async function hydrateWidgets(root, isStale = () => false) {
    const disposers = [];
    const select = type => Array.from(root.querySelectorAll(`[data-md-widget="${type}"]`));
    const jobs = [];

    const formulas = select("math");
    if (formulas.length) jobs.push(renderMath(formulas));

    const diagrams = select("mermaid");
    if (diagrams.length) jobs.push(renderMermaid(diagrams, isStale));

    const charts = select("echarts");
    if (charts.length) jobs.push(renderCharts(charts, isStale, disposers));

    const flowcharts = select("flowchart");
    if (flowcharts.length) jobs.push(renderFlowcharts(flowcharts, isStale));

    if (root.querySelector("i.fa")) jobs.push(import("./fontawesome"));

    // one failing library (e.g. a chunk that did not load) must not block the others
    await Promise.allSettled(jobs);

    return () => {
        for (const dispose of disposers) {
            try {
                dispose();
            }
            catch {
                // already gone
            }
        }
    };
}
